// Los cajones (games/cajones.tsx): a keepsake for each lesson, kept in its
// drawer, wrapped in tissue paper while the lesson is begun and unwrapped
// once it is finished (lib/colecciones.ts). Opening the drawer says the
// keepsake's Spanish: a word of the bank where there is one that fits,
// else listed in lib/spoken.ts to be recorded.
//
// Plain data, so that scripts/speech.ts can read it.

